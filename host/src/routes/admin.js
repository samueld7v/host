router.post('/keys/generate', adminAuth, async (req, res) => {
    try {
        const { duration, plan_type, count, prefix } = req.body;
        if (!duration || !plan_type || !count) return res.status(400).json({ error: 'Missing required fields' });
        if (count > 100) return res.status(400).json({ error: 'Max 100 keys per batch' });
        const keys = await KeyManager.createKeysBulk({
            count, duration, planType: plan_type, prefix: prefix || '', createdBy: req.admin.username
        });
        await KeyManager.logAction({
            key: 'bulk:' + count, hwid: '', ip: req.ip,
            action: 'generate_keys', status: 'success',
            details: `${count} keys generated by ${req.admin.username}`
        });
        res.json({ keys, count: keys.length });
    } catch (err) {
        console.error('[GENERATE]', err);
        res.status(500).json({ error: 'Internal error' });
    }
});

