const express = require('express');
const router = express.Router();
const bcrypt = require('bcrypt');
const jwt = require('jsonwebtoken');
const { pool } = require('../config/database');
const KeyManager = require('../models/KeyManager');
const { adminAuth, rateLimiter, validateRequest } = require('../middleware/security');

router.post('/login', rateLimiter(5), async (req, res) => {
    try {
        const { username, password } = req.body;
        if (!username || !password) return res.status(400).json({ error: 'Missing credentials' });
        const { rows } = await pool.query('SELECT * FROM admins WHERE username = $1', [username]);
        if (rows.length === 0 || !bcrypt.compareSync(password, rows[0].password_hash)) {
            return res.status(401).json({ error: 'Invalid credentials' });
        }
        const admin = rows[0];
        await pool.query('UPDATE admins SET last_login = NOW() WHERE id = $1', [admin.id]);
        const token = jwt.sign(
            { id: admin.id, username: admin.username, role: admin.role },
            process.env.JWT_SECRET || 'jwt-secret-change-me',
            { expiresIn: '24h' }
        );
        res.json({ token, admin: { username: admin.username, role: admin.role } });
    } catch (err) {
        console.error('[LOGIN]', err);
        res.status(500).json({ error: 'Internal error' });
    }
});

