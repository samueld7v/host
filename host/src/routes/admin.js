router.post('/admin/change-password', adminAuth, async (req, res) => {
    try {
        const { currentPassword, newPassword } = req.body;
        if (!currentPassword || !newPassword) return res.status(400).json({ error: 'Missing passwords' });
        const { rows } = await pool.query('SELECT * FROM admins WHERE id = $1', [req.admin.id]);
        if (rows.length === 0 || !bcrypt.compareSync(currentPassword, rows[0].password_hash)) {
            return res.status(401).json({ error: 'Current password is incorrect' });
        }
        if (newPassword.length < 6) return res.status(400).json({ error: 'Password must be at least 6 characters' });
        const hash = bcrypt.hashSync(newPassword, 12);
        await pool.query('UPDATE admins SET password_hash = $1 WHERE id = $2', [hash, req.admin.id]);
        res.json({ success: true, message: 'Password changed' });
    } catch (err) {
        res.status(500).json({ error: 'Internal error' });
    }
});

